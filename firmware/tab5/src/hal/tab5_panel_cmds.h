// ---------------------------------------------------------------------------
// Sitronix TDDI panels (ST7121 / ST7123).
//
// SOURCE CHANGED 2026-08-08: these two tables now come from M5Stack's OWN
// display library, not from espp. espp knows about only one Sitronix variant
// ("ST7123") and selects it purely on "something ACKs at I2C 0x55". M5Stack's
// M5GFX -- the vendor's own library for this exact board -- knows about TWO
// mutually incompatible Sitronix variants that BOTH answer at 0x55, with
// different register tables, different DSI lane rates and different DPI
// timing. Driving one with the other's table produces a panel that ACKs every
// command and displays nothing, which is the symptom this change targets.
//
// Fetched 2026-08-08 via `curl raw.githubusercontent.com`:
//   https://github.com/m5stack/M5GFX/blob/master/src/lgfx/v1/platforms/esp32p4/Panel_ST7123.hpp
//   https://github.com/m5stack/M5GFX/blob/master/src/lgfx/v1/platforms/esp32p4/Panel_ST7121.hpp
//   https://github.com/m5stack/M5GFX/blob/master/src/lgfx/v1/platforms/esp32p4/Panel_DSI.cpp
//     -> Panel_DSI::init_panel(), which walks getInitParams(0..n) sending each
//        list, sleeps getInitDelay(i) after each list, then writes MADCTL and
//        COLMOD itself, and only then calls esp_lcd_panel_init().
//
// The M5GFX lists are in LovyanGFX's "{len(cmd+params), cmd, params...}" wire
// format. They were parsed programmatically (/tmp/gen2.py + /tmp/gen3.py,
// throwaway), with the CMD_* symbols resolved out of Panel_DSI.hpp's own
// `static constexpr uint8_t CMD_x = 0x..;` declarations, and the parse
// round-trip verified -- re-serializing each parsed list reproduced the
// original token stream exactly:
//
//   Panel_ST7123.hpp  list0: 23 cmds   list1: 3 cmds        roundtrip_ok=True
//   Panel_ST7121.hpp  list0: 27 cmds   list1/2/3: 1 each    roundtrip_ok=True
//
// The per-list delays from getInitDelay() are folded onto the LAST command of
// each list, which is where init_panel() actually applies them.
//
// CROSS-CHECK: M5GFX's ST7123 list0 (23 register commands) is byte-for-byte
// IDENTICAL to the 23 register commands espp shipped -- verified
// programmatically, zero mismatches. So the register table itself was never
// the problem. What differs is (a) the existence of the ST7121 variant at all,
// (b) the tail sequence below, and (c) the lane rate / pixel clock, which live
// in boards/tab5/pins_config.h.
//
// Tail differences from espp, all resolved in the vendor's favour:
//   * espp sent SLPOUT (0x11) and DISPON (0x29) each with a spurious 1-byte
//     0x00 parameter. Both are zero-parameter DCS commands; the extra byte
//     changes the DSI data type from "DCS short write, no parameter" (0x05)
//     to "DCS short write, 1 parameter" (0x15). M5GFX sends them with no
//     parameters at all.
//   * Order. espp: SLPOUT, DISPON, TEON. M5GFX ST7123: DISPON, TEON, SLPOUT
//     then 120 ms. M5GFX ST7121: SLPOUT +80 ms, DISPON +800 ms, TEON.
//
// MADCTL/COLMOD are appended to each table because Panel_DSI::init_panel()
// writes them immediately after the lists and before esp_lcd_panel_init().
// M5GFX sets cfg.rgb_order = true for the Tab5, and init_panel() computes
// madctl_val = 0 when rgb_order is true (the BGR bit is set only when it is
// false), and colmod_val = 0x55 for 16 bpp -- the same 0x00 / 0x55 the espp
// path derived, so those two constants are unchanged.
// ---------------------------------------------------------------------------
