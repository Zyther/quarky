// These are TRANSCRIBED VERBATIM (mechanically, not by hand) from the espp
// display-driver components -- the same BSP that every other Tab5 hardware fact
// in this project is sourced from. Fetched 2026-08-07 via
// `curl raw.githubusercontent.com`:
//
//   https://github.com/esp-cpp/espp/blob/main/components/display_drivers/include/ili9881.hpp
//     -> class espp::Ili9881::initialize(), `init_commands` (202 commands)
//   https://github.com/esp-cpp/espp/blob/main/components/display_drivers/include/st7123.hpp
//     -> class espp::St7123::initialize(), `init_commands` (28 commands)
//
// (pins_config.h's Task-5 research left these as an explicit TODO because it
// only established that these components existed, not where. They are not
// top-level `ili9881`/`st7123` components -- they live inside espp's shared
// `display_drivers` component, which is why the earlier search missed them.)
//
// Transcription method (so this is auditable rather than trusted): the espp
// headers were parsed programmatically, `static_cast<uint8_t>(Command::x)`
// symbols resolved against each class's own `enum class Command : uint8_t`,
// and the parse round-trip-verified -- re-serializing the parsed entries
// reproduced the original source block byte-for-byte after whitespace
// normalization. No command byte was typed by hand.
//
// Two values in the espp tables are computed at runtime rather than literal;
// they are resolved here to the constants that the Tab5 board config produces:
//
//   MADCTL (0x36 parameter) = 0x00
//     espp computes it as make_madctl_base(config, <bgr bit>, GS_BIT, SS_BIT, 0)
//     then apply_standard_rotation(..., DisplayRotation::LANDSCAPE, ...).
//     m5stack-tab5.hpp sets swap_color_order=false, mirror_x=false,
//     mirror_y=false, swap_xy=false, so make_madctl_base() ORs in nothing and
//     returns 0; apply_standard_rotation()'s LANDSCAPE case is a no-op.
//     Net: 0x00. (Source: components/display_drivers/include/display_drivers.hpp
//     make_madctl_base()/apply_standard_rotation(); m5stack-tab5.hpp ~684-689.)
//
//   COLMOD (0x3A parameter) = 0x55
//     espp maps config_.bits_per_pixel -> colmod; the Config default is 16 and
//     the Tab5 BSP never overrides it, and 16 -> 0x55 (RGB565).
//     (Source: display_drivers.hpp Config::bits_per_pixel{16}; ili9881.hpp /
//     st7123.hpp initialize().)
//
// Both tables are sent over the MIPI-DSI DBI ("generic") command channel with
// esp_lcd_panel_io_tx_param(), which is exactly what espp's
// M5StackTab5::dsi_write_command() does with the same command/param bytes.
// -----------------------------------------------------------------------------

